const dicts: Record<Lang, Dict> = { ar, fr, en };

type I18nState = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  isRTL: boolean;
};

export const useI18n = create<I18nState>((set, get) => ({
  lang: 'ar',
  isRTL: true,
  setLang: (lang) => {
    const rtl = lang === 'ar';
    AsyncStorage.setItem('sarad.lang', lang).catch(() => {});
    if (I18nManager.isRTL !== rtl) {
      I18nManager.forceRTL(rtl);
      I18nManager.allowRTL(rtl);
    }
    set({ lang, isRTL: rtl });
  },
  t: (key) => dicts[get().lang][key] ?? dicts.en[key] ?? key,
}));

export async function hydrateLang() {
  const saved = (await AsyncStorage.getItem('sarad.lang')) as Lang | null;
  if (saved && dicts[saved]) useI18n.getState().setLang(saved);
}

